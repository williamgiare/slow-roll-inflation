"""
closed_formula_high_order_check.py

High-order exact tests of the closed Bell-polynomial/Faa di Bruno formula.

This file tests the closed relation itself,

    T_{n+1} = T_1 sum_{q=1}^n (-1)^q q! B_{n,q}(R_1,...,R_{n-q+1}),

against the direct recursive hierarchy

    T_1' = T_1 (T_1 - S_1).
"""

from __future__ import annotations

import random
from fractions import Fraction
from math import comb
from typing import Dict, List, Sequence


def random_fraction(
    rng: random.Random,
    low: int = -5,
    high: int = 5,
    nonzero: bool = False,
) -> Fraction:
    """Return a small random exact rational number."""
    if high < 1:
        raise ValueError("high must be >= 1")

    num = 0
    while num == 0 and nonzero:
        num = rng.randint(low, high)

    if not nonzero:
        num = rng.randint(low, high)

    den = rng.randint(1, max(2, high))
    return Fraction(num, den)


def derivative_of_jet_product(
    a: Sequence[Fraction],
    b: Sequence[Fraction],
    n: int,
) -> Fraction:
    """
    Return D^n(A B) at the pivot, given jets a[j]=D^j A and b[j]=D^j B.
    """
    return sum(
        Fraction(comb(n, j), 1) * a[j] * b[n - j]
        for j in range(n + 1)
    )


def build_complete_bell_values(
    scalar_jet: List[Fraction],
    max_n: int,
) -> List[Fraction]:
    """
    Build P_n = B_n(S_1,...,S_n) at the pivot.

    Since P_n is the coefficient multiplying Z in

        Z^{(n)} = P_n Z - Q_n,

    it obeys

        P_0 = 1,
        P_{n+1} = P_n' + S_1 P_n.

    Numerically, this is equivalent to the complete Bell polynomial recursion.
    The returned list has P[n] = P_n.
    """
    if len(scalar_jet) <= max_n:
        raise ValueError("Need scalar_jet up to at least S_max_n")

    # P_jets[m][a] will store D^a P_m.
    # We need enough derivative information to build Q_n and R_n.
    p_jets: List[List[Fraction]] = []

    # P_0 = 1, so D^0 P_0 = 1 and higher derivatives vanish.
    p0 = [Fraction(0, 1) for _ in range(max_n + 1)]
    p0[0] = Fraction(1, 1)
    p_jets.append(p0)

    for m in range(0, max_n):
        # P_{m+1} = P_m' + S_1 P_m.
        next_jet = [Fraction(0, 1) for _ in range(max_n + 1)]

        for a in range(0, max_n + 1):
            derivative_part = (
                p_jets[m][a + 1]
                if a + 1 <= max_n
                else Fraction(0, 1)
            )

            product_part = sum(
                Fraction(comb(a, j), 1)
                * scalar_jet[j + 1]
                * p_jets[m][a - j]
                for j in range(a + 1)
            )

            next_jet[a] = derivative_part + product_part

        p_jets.append(next_jet)

    return [p_jets[n][0] for n in range(max_n + 1)]


def build_p_jets(
    scalar_jet: List[Fraction],
    max_n: int,
) -> List[List[Fraction]]:
    """
    Build derivative jets of P_n = B_n(S_1,...,S_n).

    Returns p_jets[n][a] = D^a P_n at the pivot.
    """
    if len(scalar_jet) <= 2 * max_n + 2:
        raise ValueError("Need a longer scalar_jet for high-order P derivatives")

    p_jets: List[List[Fraction]] = []

    p0 = [Fraction(0, 1) for _ in range(max_n + 1)]
    p0[0] = Fraction(1, 1)
    p_jets.append(p0)

    for m in range(0, max_n):
        next_jet = [Fraction(0, 1) for _ in range(max_n + 1)]

        for a in range(0, max_n + 1):
            derivative_part = (
                p_jets[m][a + 1]
                if a + 1 <= max_n
                else Fraction(0, 1)
            )

            product_part = sum(
                Fraction(comb(a, j), 1)
                * scalar_jet[j + 1]
                * p_jets[m][a - j]
                for j in range(a + 1)
            )

            next_jet[a] = derivative_part + product_part

        p_jets.append(next_jet)

    return p_jets


def build_R_values_from_PQ(
    nt0: Fraction,
    scalar_jet: List[Fraction],
    max_n: int,
) -> List[Fraction]:
    """
    Build R_m = P_m - T_1 Q_m at the pivot, for m=1,...,max_n.

    Here

        Q_m = sum_{a=0}^{m-1} D^a P_{m-1-a}.

    The returned list is indexed as R[m] = R_m, with R[0] unused.
    """
    p_jets = build_p_jets(scalar_jet, max_n)

    R = [Fraction(0, 1) for _ in range(max_n + 1)]

    for m in range(1, max_n + 1):
        P_m = p_jets[m][0]

        Q_m = sum(
            p_jets[m - 1 - a][a]
            for a in range(m)
        )

        R[m] = P_m - nt0 * Q_m

    return R


def closed_formula_values_via_generating_function(
    nt0: Fraction,
    R: List[Fraction],
    max_index: int,
) -> List[Fraction]:
    """
    Evaluate the closed Bell/Faa di Bruno formula without symbolic expansion.

    We use the generating-function identity for the inverse map.

    If Z^{(m)} = Z R_m and T_1 = Z^{-1}, then the normalized derivatives
    of T_1 are generated by the inverse of the series

        1 + sum_{m>=1} R_m x^m/m!.

    This is equivalent to the Bell/Faa di Bruno formula

        T_{n+1} = T_1 sum_q (-1)^q q! B_{n,q}(R_1,...).

    The returned list is [T_1, T_2, ..., T_max_index].
    """
    if max_index < 1:
        raise ValueError("max_index must be >= 1")

    if len(R) <= max_index:
        raise ValueError("Need R up to at least R_max_index")

    # a[n] are exponential-generating coefficients of
    # A(x) = 1 + sum R_n x^n/n!.
    # b[n] are exponential-generating coefficients of B(x)=1/A(x).
    # In jet notation, b[n] is exactly the factor multiplying T_1 in T_{n+1}.
    b = [Fraction(0, 1) for _ in range(max_index)]
    b[0] = Fraction(1, 1)

    for n in range(1, max_index):
        b[n] = -sum(
            Fraction(comb(n, j), 1) * R[j] * b[n - j]
            for j in range(1, n + 1)
        )

    return [nt0 * b[n] for n in range(max_index)]


def build_riccati_tensor_jet(
    nt0: Fraction,
    scalar_jet: List[Fraction],
    max_index: int,
) -> List[Fraction]:
    """
    Build [T_1, ..., T_max_index] from the direct Riccati recursion.
    """
    if max_index < 1:
        raise ValueError("max_index must be >= 1")

    if len(scalar_jet) <= max_index:
        raise ValueError("Need scalar_jet up to at least S_max_index")

    t: List[Fraction] = [nt0]

    for n in range(0, max_index - 1):
        rhs = sum(
            Fraction(comb(n, j), 1)
            * t[j]
            * (t[n - j] - scalar_jet[n - j + 1])
            for j in range(n + 1)
        )
        t.append(rhs)

    return t


def closed_formula_rational_check(
    max_index: int = 200,
    trials: int = 3,
    seed: int = 9876,
    low: int = -5,
    high: int = 5,
    verbose: bool = True,
) -> Dict[int, bool]:
    """
    Exact rational check of the closed Bell/Faa di Bruno formula.

    The returned dictionary has keys i corresponding to T_i.
    """
    if max_index < 2:
        return {}

    rng = random.Random(seed)
    status = {i: True for i in range(2, max_index + 1)}

    for trial in range(1, trials + 1):
        nt0 = random_fraction(rng, low=low, high=high, nonzero=True)

        # We use a longer scalar jet because R_m requires derivatives of P_n.
        scalar_jet = [Fraction(0, 1)]
        scalar_jet.extend(
            random_fraction(rng, low=low, high=high, nonzero=False)
            for _ in range(2 * max_index + 5)
        )

        R = build_R_values_from_PQ(
            nt0=nt0,
            scalar_jet=scalar_jet,
            max_n=max_index,
        )

        t_closed = closed_formula_values_via_generating_function(
            nt0=nt0,
            R=R,
            max_index=max_index,
        )

        t_riccati = build_riccati_tensor_jet(
            nt0=nt0,
            scalar_jet=scalar_jet,
            max_index=max_index,
        )

        for i in range(2, max_index + 1):
            if t_closed[i - 1] != t_riccati[i - 1]:
                status[i] = False

        if verbose:
            failed = [i for i, ok in status.items() if not ok]
            if failed:
                print(
                    f"Rational trial {trial}/{trials}: failed first at T_{failed[0]}"
                )
            else:
                print(
                    f"Rational trial {trial}/{trials}: passed through T_{max_index}"
                )

    return status


