def inv_mod(a: int, p: int) -> int:
    """Return the inverse of a modulo prime p."""
    return pow(a % p, p - 2, p)


def build_R_values_mod(
    nt0: int,
    scalar_jet: List[int],
    max_n: int,
    p: int,
) -> List[int]:
    """
    Modular version of R_m = P_m - T_1 Q_m.
    """
    if len(scalar_jet) <= 2 * max_n + 2:
        raise ValueError("Need a longer scalar_jet")

    p_jets: List[List[int]] = []

    p0 = [0 for _ in range(max_n + 1)]
    p0[0] = 1 % p
    p_jets.append(p0)

    for m in range(0, max_n):
        next_jet = [0 for _ in range(max_n + 1)]

        for a in range(0, max_n + 1):
            derivative_part = p_jets[m][a + 1] if a + 1 <= max_n else 0

            product_part = 0
            for j in range(a + 1):
                product_part += (
                    comb(a, j)
                    * scalar_jet[j + 1]
                    * p_jets[m][a - j]
                )

            next_jet[a] = (derivative_part + product_part) % p

        p_jets.append(next_jet)

    R = [0 for _ in range(max_n + 1)]

    for m in range(1, max_n + 1):
        P_m = p_jets[m][0]
        Q_m = sum(
            p_jets[m - 1 - a][a]
            for a in range(m)
        ) % p
        R[m] = (P_m - nt0 * Q_m) % p

    return R


def closed_formula_values_mod(
    nt0: int,
    R: List[int],
    max_index: int,
    p: int,
) -> List[int]:
    """
    Modular evaluation of the closed Bell/Faa di Bruno formula.
    """
    b = [0 for _ in range(max_index)]
    b[0] = 1 % p

    for n in range(1, max_index):
        total = 0
        for j in range(1, n + 1):
            total += comb(n, j) * R[j] * b[n - j]
        b[n] = (-total) % p

    return [(nt0 * b[n]) % p for n in range(max_index)]


def build_riccati_tensor_jet_mod(
    nt0: int,
    scalar_jet: List[int],
    max_index: int,
    p: int,
) -> List[int]:
    """
    Modular Riccati hierarchy.
    """
    t = [nt0 % p]

    for n in range(0, max_index - 1):
        total = 0
        for j in range(n + 1):
            total += (
                comb(n, j)
                * t[j]
                * (t[n - j] - scalar_jet[n - j + 1])
            )
        t.append(total % p)

    return t


def closed_formula_modular_check(
    max_index: int = 1000,
    primes: Sequence[int] = (1000003, 1000033, 1000037),
    seed: int = 2468,
    verbose: bool = True,
) -> bool:
    """
    High-order exact finite-field check of the closed formula.

    This evaluates the closed relation modulo several primes and compares it
    with the Riccati hierarchy through T_max_index.
    """
    if max_index < 2:
        return True

    rng = random.Random(seed)

    for p in primes:
        nt0 = rng.randrange(1, p)

        scalar_jet = [0]
        scalar_jet.extend(
            rng.randrange(0, p)
            for _ in range(2 * max_index + 5)
        )

        R = build_R_values_mod(
            nt0=nt0,
            scalar_jet=scalar_jet,
            max_n=max_index,
            p=p,
        )

        t_closed = closed_formula_values_mod(
            nt0=nt0,
            R=R,
            max_index=max_index,
            p=p,
        )

        t_riccati = build_riccati_tensor_jet_mod(
            nt0=nt0,
            scalar_jet=scalar_jet,
            max_index=max_index,
            p=p,
        )

        if t_closed != t_riccati:
            if verbose:
                for i, (a, b) in enumerate(zip(t_closed, t_riccati), start=1):
                    if a != b:
                        print(f"Modular check failed modulo {p} at T_{i}")
                        break
            return False

        if verbose:
            print(f"Modular check modulo {p}: passed through T_{max_index}")

    return True


def main() -> None:
    rational_max_index = 200
    modular_max_index = 1000

    rational_status = closed_formula_rational_check(
        max_index=rational_max_index,
        trials=3,
        seed=9876,
        verbose=True,
    )

    rational_ok = all(rational_status.values())

    print()
    print(
        f"Closed formula rational check up to T_{rational_max_index}: "
        f"{rational_ok}"
    )

    modular_ok = closed_formula_modular_check(
        max_index=modular_max_index,
        primes=(1000003, 1000033, 1000037),
        seed=2468,
        verbose=True,
    )

    print()
    print(
        f"Closed formula modular check up to T_{modular_max_index}: "
        f"{modular_ok}"
    )


if __name__ == "__main__":
    main()
