from contextlib import redirect_stdout
from functools import lru_cache
from hashlib import sha256
from pathlib import Path
import os
import pickle
import sqlite3
import sys

import mpmath as mp
import sympy as sp
from . import fast

C = fast.C


def checked_pattern(pattern):
    pattern = tuple(pattern)
    if not pattern or any(type(j) is not int or j < 0 for j in pattern):
        raise ValueError('Source logarithmic powers must be nonnegative integers.')
    return tuple(sorted(pattern))


def kernel_signature():
    digest = sha256()
    for name in ('fast.py', 'mixed_hyperlogs.py', 'generic_hyperlogs.py'):
        digest.update(name.encode())
        digest.update(Path(__file__).with_name(name).read_bytes())
    return digest.hexdigest()


def cache_directory():
    configured = os.environ.get('SRI_SYMBOLIC_CACHE')
    return Path(configured).expanduser() if configured else Path.home()/'.cache/sri/symbolic'


@lru_cache(maxsize=16)
def family(rank, degree):
    """Generate a complete exact mixed family, reusing compatible private checkpoints."""
    if type(rank) is not int or rank < 1 or type(degree) is not int or degree < 0:
        raise ValueError('Require a positive insertion rank and nonnegative log degree.')
    from . import generic_hyperlogs as general
    path = cache_directory()/kernel_signature()/f'm{rank:02d}_j{degree:02d}.pkl'
    if path.exists():
        # Private checkpoints contain only expressions generated by this backend.
        with path.open('rb') as handle:
            expressions = pickle.load(handle)
        if set(expressions) != set(general.patterns(rank, degree)):
            raise ArithmeticError('Incomplete analytic family checkpoint.')
        for value in expressions.values():
            if not isinstance(value, sp.Expr) or value.has(sp.Float, sp.Derivative, sp.Integral) or value.free_symbols-{C}:
                raise ArithmeticError('Nonexact analytic family checkpoint.')
        return expressions
    with redirect_stdout(sys.stderr):
        expressions = general.family(rank, degree)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(f'.{os.getpid()}.tmp')
    with temporary.open('wb') as handle:
        pickle.dump(expressions, handle)
    temporary.replace(path)
    return expressions


def moment(pattern):
    """Return the complete exact expression for chi_(m;pattern)."""
    pattern = checked_pattern(pattern)
    return fast.moment(pattern) if fast.supported(pattern) else family(len(pattern), sum(pattern))[pattern]


def evaluate(expression, digits=24):
    """Evaluate exact coefficients, caching standard GPL values at their working precision."""
    if type(digits) is not int or digits < 2:
        raise ValueError('Evaluation digits must be an integer of at least two.')
    from .generic_hyperlogs import GPL, Q, gpl_value
    expression = expand_coefficients(sp.sympify(expression))
    working = digits + 15
    atoms = sorted(expression.atoms(GPL), key=lambda value: (len(value.args[0]), str(value)))
    replacements = {}
    if atoms:
        path = cache_directory()/'gpl_values.sqlite'
        path.parent.mkdir(parents=True, exist_ok=True)
        with sqlite3.connect(path, timeout=60) as database:
            database.execute('CREATE TABLE IF NOT EXISTS values_cache (signature TEXT, digits INTEGER, word TEXT, value TEXT, PRIMARY KEY(signature,digits,word))')
            database.execute('CREATE INDEX IF NOT EXISTS values_cache_word_precision ON values_cache(signature,word,digits)')
            signature = kernel_signature()
            for atom in atoms:
                word = tuple(Q(int(a.p), int(a.q)) for a in atom.args[0])
                key = ','.join(map(str, word))
                saved = database.execute('SELECT value, digits FROM values_cache WHERE signature=? AND word=? AND digits>=? ORDER BY digits LIMIT 1', (signature, key, working)).fetchone()
                if saved is None:
                    number = mp.nstr(gpl_value(word, working), working)
                    database.execute('INSERT OR IGNORE INTO values_cache VALUES (?,?,?,?)', (signature, working, key, number))
                    saved = number, working
                replacements[atom] = sp.Float(saved[0], saved[1])
            database.commit()
    return expression.xreplace(replacements).subs(C, fast.C_VALUE).evalf(digits)


class Chi(sp.Function):
    """Exact universal mixed coefficient; its complete definition is moment(pattern)."""
    nargs = 1
    is_real = True

    @classmethod
    def eval(cls, pattern):
        if not isinstance(pattern, sp.Tuple):
            raise ValueError('Chi expects a tuple of nonnegative logarithmic powers.')
        if any(not j.is_Integer or j < 0 for j in pattern) or not pattern:
            raise ValueError('Chi expects a nonempty tuple of nonnegative integers.')
        canonical = sp.Tuple(*sorted(pattern))
        if canonical != pattern:
            return cls(canonical)
        key = tuple(map(int, canonical))
        if fast.supported(key):
            return fast.moment(key)

    def definition(self):
        return moment(tuple(map(int, self.args[0])))

    def _eval_evalf(self, prec):
        digits = max(2, int(prec * 0.30103) + 2)
        return evaluate(self.definition(), digits)

    def _latex(self, printer):
        pattern = self.args[0]
        return r'\chi_{' + str(len(pattern)) + ';' + ','.join(map(str, pattern)) + '}'


def expand_coefficients(expression):
    """Replace every defined Chi constant by its complete analytic expression."""
    return expression.xreplace({atom: atom.definition() for atom in expression.atoms(Chi)})


class SymbolicMomentData:
    """Exact coefficient-symbol algebra shared by both engines and physical models."""
    def __init__(self, order):
        from ..generic_modes import source_patterns
        patterns = list(source_patterns(order))
        self.order = order
        self.expressions = {key: sp.Symbol('J_'+'_'.join(map(str, key))) for key in patterns}
        self.values = {symbol: (fast.moment(key) if fast.supported(key) else Chi(sp.Tuple(*key)))
                       for key, symbol in self.expressions.items()}
        self.symbols = tuple(self.values)

    def resolve(self, expression):
        from ..background import PI2, ZETA3
        return sp.expand(expression.xreplace(self.values).xreplace({PI2: sp.pi**2, ZETA3: sp.zeta(3)}))

    def metadata(self):
        mixed = [list(key) for key in self.expressions if not fast.supported(key)]
        return {'backend': 'analytic Hankel/Mellin and mixed Goncharov generators',
                'coefficient_backend': 'symbolic', 'order': self.order,
                'moments': len(self.expressions), 'numerically_generated_moments': 0,
                'algebra': 'exact symbolic constants', 'validated_through_weight': 10,
                'mixed_patterns': mixed,
                'mixed_definition': 'Chi(pattern) = sri.analytic.moment(pattern)',
                'coefficient_origin': 'analytic generating functions; no numerical mode coefficients'}
